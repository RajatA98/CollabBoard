#!/usr/bin/env node
/**
 * Regenerates CHAT_LOG.md from Cursor agent transcripts.
 * Run from repo root: node scripts/update-chat-log.js
 * Or: npm run update-chat-log
 *
 * Transcripts path: set TRANSCRIPTS_DIR or defaults to
 * ~/.cursor/projects/Users-rajatarora-Gauntlet-CollabBoard/agent-transcripts
 */

const fs = require('fs');
const path = require('path');
const os = require('os');

const REPO_ROOT = path.resolve(__dirname, '..');
const DEFAULT_TRANSCRIPTS = path.join(
  os.homedir(),
  '.cursor',
  'projects',
  'Users-rajatarora-Gauntlet-CollabBoard',
  'agent-transcripts'
);
const TRANSCRIPTS_DIR = process.env.TRANSCRIPTS_DIR || DEFAULT_TRANSCRIPTS;
const OUTPUT_FILE = path.join(REPO_ROOT, 'CHAT_LOG.md');

function getFirstUserMessage(jsonlPath) {
  try {
    const line = fs.readFileSync(jsonlPath, 'utf8').split('\n')[0];
    if (!line) return '(no first user message)';
    const o = JSON.parse(line);
    if (o.role !== 'user' || !o.message?.content?.[0]?.text) return '(no first user message)';
    let t = o.message.content[0].text;
    const m = t.match(/<user_query>\s*([\s\S]*?)(?:<|$)/);
    if (m) t = m[1].trim();
    else t = t.replace(/\[Image\].*?<\/image_files>/s, '').replace(/<[^>]+>/g, '').trim();
    return t.slice(0, 100).replace(/\n/g, ' ').replace(/\r/g, '') + (t.length > 100 ? '...' : '');
  } catch (_) {
    return '(parse error)';
  }
}

function main() {
  if (!fs.existsSync(TRANSCRIPTS_DIR)) {
    console.error('Transcripts dir not found:', TRANSCRIPTS_DIR);
    console.error('Set TRANSCRIPTS_DIR to your agent-transcripts path.');
    process.exit(1);
  }

  const entries = [];
  const dirs = fs.readdirSync(TRANSCRIPTS_DIR, { withFileTypes: true });
  for (const d of dirs) {
    if (!d.isDirectory()) continue;
    const id = d.name;
    const jsonlPath = path.join(TRANSCRIPTS_DIR, id, `${id}.jsonl`);
    if (!fs.existsSync(jsonlPath)) continue;
    const title = getFirstUserMessage(jsonlPath);
    const mtime = fs.statSync(jsonlPath).mtimeMs;
    entries.push({ id, title, mtime });
  }

  entries.sort((a, b) => b.mtime - a.mtime);

  const lines = [
    '# CollabBoard – Chat log',
    '',
    'Log of all Cursor agent chats for this project. Transcripts live in Cursor project data.',
    'Regenerate with: `npm run update-chat-log` (from repo root). Sorted by date (newest first).',
    '',
    '---',
    ''
  ];

  for (const { id, title, mtime } of entries) {
    const date = new Date(mtime).toISOString().slice(0, 16).replace('T', ' ');
    lines.push(`### ${title}`);
    lines.push(`- **ID:** \`${id}\``);
    lines.push(`- **Date:** ${date}`);
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push('*Generated by `scripts/update-chat-log.js`. Full transcripts in Cursor project agent-transcripts.*');

  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');
  console.log('Updated CHAT_LOG.md with', entries.length, 'chats.');
}

main();
